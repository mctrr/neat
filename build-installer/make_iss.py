"""Generate the Inno Setup .iss script with per-component filter file lists."""
import json
import os

BASE = r"D:\neat-rebuild\ads-dl\filters"
OUT = r"D:\neat-rebuild\build-installer\NEAT-Installer.iss"
SRC = r"D:\neat-installer-src"

BASE_FILES = [
    "easylist.txt", "easyprivacy.txt", "ublock-filters.txt", "ublock-quick-fixes.txt",
    "ublock-unbreak.txt", "ublock-badware.txt", "urlhaus-1.txt", "resources.json",
    "ubo-resource-abuse.txt", "fanboy-thirdparty_social.txt", "popups.txt",
    "easylist-notifications.txt", "easylist-chat.txt",
]
CN_FILES = ["chn-0.txt"]
PRIVACY_FILES = [
    "fanboy-cookiemonster.txt", "adguard-cookies.txt", "ublock-privacy.txt",
    "hagezi-pro.txt", "easylist-newsletters.txt", "documents.txt",
    "ublock-cookies-adguard.txt", "easylist-annoyances.txt",
    "adguard-other-annoyances.txt", "ublock-annoyances.txt",
]

with open(os.path.join(BASE, "manifest.json"), encoding="utf-8") as f:
    full = json.load(f)
all_names = [f["name"] for f in full["files"]]
other = [n for n in all_names if n not in BASE_FILES + CN_FILES + PRIVACY_FILES]

# Component flags: each tier includes the ones before it.
C_BASE = "filters\\base filters\\base_cn filters\\base_privacy filters\\all"
C_CN = "filters\\base_cn filters\\base_privacy filters\\all"
C_PRIV = "filters\\base_privacy filters\\all"
C_ALL = "filters\\all"

lines = []
def emit(s=""):
    lines.append(s)

emit("; NEAT Browser Chinese Edition - installer script")
emit("; Generated by build-installer/make_iss.py")
emit("")
emit("#define MyAppName \"NEAT 浏览器\"")
emit("#define MyAppVersion \"0.16.0\"")
emit("#define MyAppPublisher \"Fallen\"")
emit("#define MyAppURL \"https://github.com/mctrr/neat\"")
emit("#define MyAppExeName \"neat.exe\"")
emit("")
emit("[Setup]")
emit("AppId={{8F2C4D6E-9A71-4B3C-AE5D-7C1F0B2D6E84}")
emit("AppName={#MyAppName}")
emit("AppVersion={#MyAppVersion}")
emit("AppPublisher={#MyAppPublisher}")
emit("AppPublisherURL={#MyAppURL}")
emit("AppSupportURL={#MyAppURL}")
emit("AppUpdatesURL={#MyAppURL}/releases")
emit("DefaultDirName={autopf}\\NEAT")
emit("DefaultGroupName={#MyAppName}")
emit("AllowNoIcons=yes")
emit("LicenseFile=D:\\neat-rebuild\\LICENSE")
emit("OutputDir=D:\\neat-rebuild\\build-installer\\Output")
emit("OutputBaseFilename=NEAT-Browser-0.16.0-CN-x64")
emit("SetupIconFile=D:\\neat-rebuild\\browser\\branding\\official\\default.ico")
emit("UninstallDisplayIcon={app}\\neat.exe")
emit("Compression=lzma2/max")
emit("SolidCompression=yes")
emit("WizardStyle=modern")
emit("ArchitecturesInstallIn64BitMode=x64")
emit("MinVersion=10.0.17763")
emit("")
emit("[Languages]")
emit("Name: \"chinesesimplified\"; MessagesFile: \"compiler:Languages\\ChineseSimplified.isl\"")
emit("")
emit("[Types]")
emit("Name: compact; Description: \"紧凑安装（系统内核 + 基础中文规则，推荐）\"")
emit("Name: full; Description: \"完整安装（自带内核 + 全部规则）\"")
emit("Name: custom; Description: \"自定义\"; Flags: iscustom")
emit("")
emit("[Components]")
emit("Name: core; Description: \"NEAT 浏览器核心程序（必需）\"; Types: compact full custom; Flags: fixed")
emit("Name: runtime; Description: \"自带 WebView2 内核（约 510 MB，不勾选则用系统已装的 WebView2）\"; Types: full")
emit("Name: filters; Description: \"广告过滤规则\"; Types: compact full custom; Flags: fixed")
emit('Name: filters\\base; Description: "基础规则（国际通用，约 20 MB）"')
emit('Name: filters\\base_cn; Description: "基础 + 中文规则（推荐，约 21 MB）"; Types: compact custom')
emit('Name: filters\\base_privacy; Description: "基础 + 中文 + 隐私规则（约 35 MB）"')
emit('Name: filters\\all; Description: "全部规则（约 54 MB）"; Types: full')
emit("")
emit("[Files]")
emit(f'Source: "{SRC}\\app\\*"; DestDir: "{{app}}"; Flags: recursesubdirs ignoreversion; Components: core')
emit(f'Source: "{SRC}\\neat_adblock.dll"; DestDir: "{{app}}"; Flags: ignoreversion; Components: core')
emit(f'Source: "{SRC}\\runtime\\WebView2\\*"; DestDir: "{{app}}\\WebView2"; Flags: recursesubdirs ignoreversion; Components: runtime')
emit("")
emit("; Filter lists - only the files belonging to the selected tier are installed.")
for name in BASE_FILES:
    emit(f'Source: "{SRC}\\filters\\{name}"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_BASE}')
for name in CN_FILES:
    emit(f'Source: "{SRC}\\filters\\{name}"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_CN}')
for name in PRIVACY_FILES:
    emit(f'Source: "{SRC}\\filters\\{name}"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_PRIV}')
for name in other:
    emit(f'Source: "{SRC}\\filters\\{name}"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_ALL}')
emit("; optional packs (adult) go with the full set")
emit(f'Source: "{SRC}\\filters\\optional.json"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_ALL}')
emit(f'Source: "{SRC}\\filters\\optional-adult.txt"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: {C_ALL}')
emit("; All manifest variants are staged; Code section activates the right one.")
for v in ("base", "base_cn", "base_privacy", "base_cn_privacy", "all"):
    emit(f'Source: "{SRC}\\filters\\_manifest_{v}.json"; DestDir: "{{app}}\\filters"; Flags: ignoreversion; Components: filters')
emit("")
emit("[Icons]")
emit('Name: "{group}\\NEAT 浏览器"; Filename: "{app}\\neat.exe"; WorkingDir: "{app}"')
emit('Name: "{group}\\卸载 NEAT"; Filename: "{uninstallexe}"')
emit('Name: "{autodesktop}\\NEAT 浏览器"; Filename: "{app}\\neat.exe"; WorkingDir: "{app}"; Tasks: desktopicon')
emit("")
emit("[Tasks]")
emit('Name: desktopicon; Description: "创建桌面快捷方式"; GroupDescription: "其他:"; Flags: checkedonce')
emit("")
emit("[Run]")
emit('Filename: "{app}\\neat.exe"; Description: "启动 NEAT 浏览器"; Flags: nowait postinstall skipifsilent')
emit("")
emit("[Code]")
emit("""procedure CurStepChanged(CurStep: TSetupStep);
var
  FiltersDir, Src, Dest: string;
begin
  if CurStep = ssPostInstall then
  begin
    FiltersDir := ExpandConstant('{app}\\filters');

    { Pick the manifest matching the files actually on disk. More robust than
      WizardIsComponentSelected, which misfires on reinstall / upgrade. }
    if FileExists(FiltersDir + '\\optional-adult.txt') then
      Src := '_manifest_all.json'
    else if FileExists(FiltersDir + '\\hagezi-pro.txt') then
    begin
      if FileExists(FiltersDir + '\\chn-0.txt') then
        Src := '_manifest_base_cn_privacy.json'
      else
        Src := '_manifest_base_privacy.json';
    end
    else if FileExists(FiltersDir + '\\chn-0.txt') then
      Src := '_manifest_base_cn.json'
    else if FileExists(FiltersDir + '\\easylist.txt') then
      Src := '_manifest_base.json'
    else
    begin
      MsgBox('未安装任何过滤规则文件，请在安装时勾选规则组件。', mbError, MB_OK);
      Exit;
    end;

    Dest := FiltersDir + '\\manifest.json';
    DeleteFile(Dest);
    if FileExists(FiltersDir + '\\' + Src) then
    begin
      if not FileCopy(FiltersDir + '\\' + Src, Dest, True) then
        MsgBox('无法生成过滤规则清单: ' + Src, mbError, MB_OK);
    end
    else
      MsgBox('过滤规则清单缺失: ' + Src + #13#10 + '请重新安装。', mbError, MB_OK);

    { Remove staged variants. }
    DeleteFile(FiltersDir + '\\_manifest_base.json');
    DeleteFile(FiltersDir + '\\_manifest_base_cn.json');
    DeleteFile(FiltersDir + '\\_manifest_base_privacy.json');
    DeleteFile(FiltersDir + '\\_manifest_base_cn_privacy.json');
    DeleteFile(FiltersDir + '\\_manifest_all.json');
  end;
end;""")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
print("base:", len(BASE_FILES), "cn:", len(CN_FILES), "privacy:", len(PRIVACY_FILES), "other:", len(other))
